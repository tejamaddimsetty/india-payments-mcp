import { has, lines, type GeneratedFile, type TemplateContext } from './shared.js';

/** Express (4 or 5) router + a minimal server showing the middleware order that keeps raw bodies intact. */
export function expressFiles(ctx: TemplateContext, base = 'src'): GeneratedFile[] {
  const refunds = has(ctx, 'refunds');
  const subs = has(ctx, 'subscriptions');
  const svcImports = ['confirmPayment', 'createCheckout', 'handleWebhook', 'mockComplete', 'toHttpError', ...(refunds ? ['assertAdmin', 'refundPayment'] : []), ...(subs ? ['startSubscription'] : [])];

  const router = lines(
    `/**`,
    ` * ${ctx.cap.displayName} payment routes for Express.`,
    ` *`,
    ` * Mount this router BEFORE any global \`app.use(express.json())\`: the webhook route needs the raw`,
    ` * request bytes to verify the signature, and a body parser that runs first would consume them.`,
    ` */`,
    `import express, { type Request, type Response, type NextFunction } from 'express';`,
    `import { ${svcImports.sort().join(', ')} } from './service.js';`,
    ``,
    `const RESULT_PATH = '/checkout.html';`,
    ``,
    `/** Wrap async handlers so errors become safe JSON responses (Express 4 does not catch rejections). */`,
    `const route =`,
    `  (fn: (req: Request, res: Response) => Promise<unknown>) =>`,
    `  (req: Request, res: Response, _next: NextFunction) =>`,
    `    fn(req, res).catch((err) => {`,
    `      const { status, body } = toHttpError(err);`,
    `      res.status(status).json(body);`,
    `    });`,
    ``,
    `/** Express gives repeated query keys as arrays; gateways never send those, so keep the first. */`,
    `function flatten(input: unknown): Record<string, string> {`,
    `  const out: Record<string, string> = {};`,
    `  if (!input || typeof input !== 'object') return out;`,
    `  for (const [k, v] of Object.entries(input as Record<string, unknown>)) {`,
    `    const first = Array.isArray(v) ? v[0] : v;`,
    `    if (first !== undefined && first !== null && typeof first !== 'object') out[k] = String(first);`,
    `  }`,
    `  return out;`,
    `}`,
    ``,
    `export function paymentsRouter(): express.Router {`,
    `  const r = express.Router();`,
    ``,
    `  // Webhook: express.raw keeps the exact bytes as a Buffer. Never JSON.parse + re-stringify before verifying.`,
    `  r.post(`,
    `    '/api/payments/webhook',`,
    `    express.raw({ type: '*/*', limit: '1mb' }),`,
    `    route(async (req, res) => {`,
    `      if (!Buffer.isBuffer(req.body)) {`,
    `        // A global body parser ran first. Fix the middleware order instead of re-serialising.`,
    `        throw new Error('Webhook body was already parsed: mount paymentsRouter() before express.json().');`,
    `      }`,
    `      const result = await handleWebhook({`,
    `        headers: req.headers,`,
    `        rawBody: req.body.toString('utf8'),`,
    `      });`,
    `      res.status(result.status).json(result.body);`,
    `    }),`,
    `  );`,
    ``,
    `  // Everything else takes JSON (our own fetch calls) or form posts (gateway returns).`,
    `  r.use('/api/payments', express.json({ limit: '100kb' }), express.urlencoded({ extended: false, limit: '100kb' }));`,
    ``,
    `  r.post(`,
    `    '/api/payments/create',`,
    `    route(async (req, res) => {`,
    `      res.status(201).json(await createCheckout(req.body));`,
    `    }),`,
    `  );`,
    ``,
    `  // Return URL. Gateways arrive as a form POST (PayU, CCAvenue, Paytm, Razorpay redirect mode) or a GET`,
    `  // redirect (Cashfree, PhonePe, Stripe); our own JS (Razorpay modal handler) POSTs JSON.`,
    `  const callback = route(async (req, res) => {`,
    `    const result = await confirmPayment(flatten(req.query), req.method === 'POST' ? flatten(req.body) : {});`,
    `    if (req.is('application/json') || req.accepts(['html', 'json']) === 'json') {`,
    `      res.status(result.orderRef ? 200 : 400).json(result);`,
    `      return;`,
    `    }`,
    `    // 303 turns the gateway's POST into a GET of the result page (no "resubmit form?" on reload).`,
    `    const q = new URLSearchParams({ orderRef: result.orderRef ?? '', status: result.status });`,
    `    res.redirect(303, \`\${RESULT_PATH}?\${q}\`);`,
    `  });`,
    `  r.post('/api/payments/callback', callback);`,
    `  r.get('/api/payments/callback', callback);`,
    refunds
      ? lines(
          ``,
          `  // Admin only. Replace assertAdmin with your real auth (session + role).`,
          `  r.post(`,
          `    '/api/payments/refund',`,
          `    route(async (req, res) => {`,
          `      assertAdmin(req.get('authorization'));`,
          `      res.json(await refundPayment(req.body));`,
          `    }),`,
          `  );`,
        )
      : false,
    subs
      ? lines(
          ``,
          `  r.post(`,
          `    '/api/payments/subscription',`,
          `    route(async (req, res) => {`,
          `      // TODO: require a logged-in customer here.`,
          `      res.status(201).json(await startSubscription(req.body));`,
          `    }),`,
          `  );`,
        )
      : false,
    ``,
    `  // Dev only: returns 404 unless PAYMENTS_MODE=mock.`,
    `  r.post(`,
    `    '/api/payments/mock-complete',`,
    `    route(async (req, res) => {`,
    `      res.json(await mockComplete(req.body));`,
    `    }),`,
    `  );`,
    ``,
    `  return r;`,
    `}`,
    ``,
  );

  const server = lines(
    `/**`,
    ` * Minimal Express app wiring the payment routes. Run: npx tsx ${base}/server.ts`,
    ` */`,
    `import express from 'express';`,
    `import { paymentsRouter } from './payments/routes.js';`,
    ``,
    `const app = express();`,
    `app.disable('x-powered-by');`,
    `// Behind a proxy / tunnel (ngrok, Cloudflare), trust it so req.protocol and req.ip are right.`,
    `app.set('trust proxy', 1);`,
    ``,
    `// 1. Payments first: its webhook route reads the raw body.`,
    `app.use(paymentsRouter());`,
    `// 2. Then your global parsers and the rest of your app.`,
    `app.use(express.json());`,
    `app.use(express.static('public'));`,
    ``,
    `const port = Number(process.env.PORT ?? 3000);`,
    `app.listen(port, () => {`,
    `  console.log(\`Checkout on http://localhost:\${port}/checkout.html (PAYMENTS_MODE=\${process.env.PAYMENTS_MODE ?? 'sandbox'})\`);`,
    `});`,
    ``,
  );

  return [
    { path: `${base}/payments/routes.ts`, language: 'typescript', contents: router },
    { path: `${base}/server.ts`, language: 'typescript', contents: server },
  ];
}
