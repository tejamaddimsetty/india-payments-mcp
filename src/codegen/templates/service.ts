import { profileFor } from './profiles.js';
import { has, lines, SDK_PACKAGE, type TemplateContext } from './shared.js';

/** Providers whose webhook body is not cryptographically signed: re-fetch status before trusting it. */
const UNSIGNED_WEBHOOK_BODY = new Set(['phonepe', 'ccavenue']);

/**
 * The framework-agnostic payments service. Express, Next.js and Fastify routes are thin wrappers
 * around these functions so the security-sensitive logic exists exactly once.
 *
 * `singleton` = true wraps the client in a globalThis cache (Next.js dev compiles each route
 * separately, which would otherwise create one client and one mock ledger per route).
 */
export function serviceModule(ctx: TemplateContext, opts: { singleton: boolean; resultPath: string }): string {
  const { cap } = ctx;
  const profile = profileFor(cap.provider);
  const refunds = has(ctx, 'refunds');
  const subs = has(ctx, 'subscriptions');
  const needsPhone = ['cashfree', 'payu', 'paytm'].includes(cap.provider);
  const orderRefField = profile.orderRefField;

  return lines(
    `/**`,
    ` * Payments service: ${cap.displayName} via ${SDK_PACKAGE}.`,
    ` *`,
    ` * Every route in this app is a thin wrapper around the functions below, so the rules that keep`,
    ` * money safe live in one place:`,
    ` *   1. The amount ALWAYS comes from getOrderAmount() on the server, never from the browser.`,
    ` *   2. A payment is "paid" only after verifyPayment() passes with the expected orderRef + amount`,
    ` *      AND the gateway's status API (or a signed webhook) says captured.`,
    ` *   3. Fulfilment is idempotent: callbacks, retries and webhooks can arrive in any order, twice.`,
    ` *`,
    ` * ${profile.trustNote}`,
    ` */`,
    `import { randomBytes, timingSafeEqual } from 'node:crypto';`,
    `import {`,
    `  createPaymentsClient,`,
    `  createWebhookHandler,`,
    `  PaymentError,`,
    `  type CheckoutAction,`,
    `  type Customer,`,
    `  type NormalizedWebhookEvent,`,
    `  type PaymentStatus,`,
    `  type PaymentsClient,`,
    `} from '${SDK_PACKAGE}';`,
    ``,
    `export const PROVIDER = '${cap.provider}' as const;`,
    ``,
    opts.singleton
      ? lines(
          `// One client per server process. It reads PAYMENTS_MODE and the ${cap.displayName} credentials from`,
          `// process.env. Cached on globalThis because Next.js dev compiles each route module separately.`,
          `const globalForPayments = globalThis as unknown as { __payments?: PaymentsClient };`,
          `export const payments: PaymentsClient = (globalForPayments.__payments ??= createPaymentsClient({ actor: 'web' }));`,
        )
      : lines(
          `// One client per server process. It reads PAYMENTS_MODE and the ${cap.displayName} credentials`,
          `// (${cap.credentials.map((c) => c.env).join(', ')}) from process.env.`,
          `export const payments: PaymentsClient = createPaymentsClient({ actor: 'web' });`,
        ),
    ``,
    `/** Thrown by the service; routes turn it into an HTTP response. */`,
    `export class HttpError extends Error {`,
    `  constructor(readonly status: number, message: string) {`,
    `    super(message);`,
    `  }`,
    `}`,
    ``,
    `/** Map any error to a safe HTTP status + JSON body. Never leaks provider internals to the browser. */`,
    `export function toHttpError(err: unknown): { status: number; body: { error: string; message: string } } {`,
    `  if (err instanceof HttpError) return { status: err.status, body: { error: 'REQUEST_FAILED', message: err.message } };`,
    `  if (err instanceof PaymentError) {`,
    `    payments.logger.error('payments.error', { code: err.code, message: err.message });`,
    `    const status = err.code === 'VALIDATION' ? 400 : err.code === 'NOT_FOUND' ? 404 : err.code === 'LIVE_MUTATION_BLOCKED' ? 403 : 502;`,
    `    return { status, body: { error: err.code, message: status === 502 ? 'Payment gateway error, please retry.' : err.message } };`,
    `  }`,
    `  payments.logger.error('payments.unexpected_error', { err: String(err) });`,
    `  return { status: 500, body: { error: 'INTERNAL', message: 'Something went wrong.' } };`,
    `}`,
    ``,
    `function baseUrl(): string {`,
    `  const url = process.env.PUBLIC_BASE_URL;`,
    `  if (!url) throw new HttpError(500, 'PUBLIC_BASE_URL is not set: the gateway needs an absolute URL to send the customer back to.');`,
    `  return url.replace(/\\/+$/, '');`,
    `}`,
    ``,
    `// ------------------------------------------------------------------------------------------`,
    `// Your data layer. Replace these in-memory stubs with your database (Postgres, Prisma, ...).`,
    `// ------------------------------------------------------------------------------------------`,
    ``,
    `/** One row per payment ATTEMPT. A customer retrying checkout creates a new attempt (gateways need a unique id per attempt). */`,
    `export interface PaymentAttempt {`,
    `  /** Sent to the gateway as its order id. Unique per attempt, 3-40 chars [A-Za-z0-9_-]. */`,
    `  orderRef: string;`,
    `  /** Your own order / cart id. */`,
    `  orderId: string;`,
    `  /** Integer paise, copied from YOUR order record at creation time. */`,
    `  amount: number;`,
    `  currency: string;`,
    `  providerOrderId?: string;`,
    `  providerPaymentId?: string;`,
    `  status: PaymentStatus;`,
    `  refundedAmount: number;`,
    `}`,
    ``,
    `const DEMO_ORDERS: Record<string, { amount: number; currency: string; description: string; customer: Customer }> = {`,
    `  'demo-order-1': {`,
    `    amount: 49900, // Rs 499.00 in paise`,
    `    currency: 'INR',`,
    `    description: 'Demo order',`,
    `    customer: { id: 'cust_demo_1', name: 'Test Customer', email: 'test@example.com', phone: '9999999999' },`,
    `  },`,
    `};`,
    ``,
    `/**`,
    ` * THE source of truth for what the customer owes. Never take amount or currency from the request`,
    ` * body: anyone can edit it in DevTools and pay Rs 1 for a Rs 10,000 order.`,
    ` */`,
    `export async function getOrderAmount(orderId: string): Promise<{ amount: number; currency: string; description: string }> {`,
    `  // TODO: SELECT total_paise, currency, description FROM orders WHERE id = $1 AND status = 'awaiting_payment'`,
    `  const order = DEMO_ORDERS[orderId];`,
    `  if (!order) throw new HttpError(404, \`Unknown or already-paid order \${orderId}\`);`,
    `  return { amount: order.amount, currency: order.currency, description: order.description };`,
    `}`,
    ``,
    `/** Customer details for the gateway${needsPhone ? ` (${cap.displayName} requires a phone number)` : ''}. Read them from your user record, not the request. */`,
    `async function getOrderCustomer(orderId: string): Promise<Customer | undefined> {`,
    `  // TODO: load from the logged-in user / order record.`,
    `  return DEMO_ORDERS[orderId]?.customer;`,
    `}`,
    ``,
    `const attempts = new Map<string, PaymentAttempt>(); // TODO: a payment_attempts table keyed by order_ref`,
    ``,
    `async function saveAttempt(attempt: PaymentAttempt): Promise<void> {`,
    `  attempts.set(attempt.orderRef, { ...attempt });`,
    `}`,
    ``,
    `export async function findAttempt(orderRef: string): Promise<PaymentAttempt | undefined> {`,
    `  const a = attempts.get(orderRef);`,
    `  return a ? { ...a } : undefined;`,
    `}`,
    ``,
    `/** Some webhooks identify the order only by the gateway's id (e.g. Razorpay payment.* events). */`,
    `async function findAttemptByProviderOrderId(providerOrderId: string): Promise<PaymentAttempt | undefined> {`,
    `  for (const a of attempts.values()) if (a.providerOrderId === providerOrderId) return { ...a };`,
    `  return undefined;`,
    `}`,
    ``,
    `/** Ship the goods / unlock the plan. MUST be idempotent: it can be reached from the callback AND the webhook. */`,
    `async function fulfilOrder(attempt: PaymentAttempt): Promise<void> {`,
    `  // TODO: UPDATE orders SET status = 'paid' WHERE id = $1 AND status <> 'paid'; then email the receipt.`,
    `  payments.logger.info('order.fulfilled', { orderId: attempt.orderId, orderRef: attempt.orderRef, amount: attempt.amount });`,
    `}`,
    ``,
    `// ------------------------------------------------------------------------------------------`,
    `// 1. Create a payment (POST /api/payments/create)`,
    `// ------------------------------------------------------------------------------------------`,
    ``,
    `export interface CreateCheckoutResponse {`,
    `  orderRef: string;`,
    `  provider: typeof PROVIDER;`,
    `  mode: 'mock' | 'sandbox' | 'live';`,
    `  amount: number;`,
    `  currency: string;`,
    `  /** What the browser must do next. Contains only publishable values. */`,
    `  checkout: CheckoutAction;`,
    `}`,
    ``,
    `export async function createCheckout(body: unknown): Promise<CreateCheckoutResponse> {`,
    `  const orderId = (body as { orderId?: unknown } | null)?.orderId;`,
    `  if (typeof orderId !== 'string' || !/^[A-Za-z0-9_-]{1,24}$/.test(orderId)) {`,
    `    throw new HttpError(400, 'orderId must be 1-24 characters of letters, digits, "_" or "-".');`,
    `  }`,
    `  // The browser only tells us WHICH order. The price comes from our own records.`,
    `  const { amount, currency, description } = await getOrderAmount(orderId);`,
    `  const customer = await getOrderCustomer(orderId);`,
    ``,
    `  // Unique per attempt: gateways reject a re-used order id once a payment was tried on it.`,
    `  const orderRef = \`\${orderId}_\${randomBytes(6).toString('hex')}\`;`,
    `  const created = await payments.createPayment(PROVIDER, {`,
    `    orderRef,`,
    `    amount,`,
    `    currency,`,
    `    description,`,
    `    customer,`,
    `    // Where the gateway sends the customer back. Our own orderRef rides along in the query string`,
    `    // so the callback knows which attempt (and therefore which amount) to verify against.`,
    `    returnUrl: \`\${baseUrl()}/api/payments/callback?orderRef=\${encodeURIComponent(orderRef)}\`,`,
    `    notifyUrl: \`\${baseUrl()}/api/payments/webhook\`,`,
    `    metadata: { order_id: orderId },`,
    `    idempotencyKey: orderRef,`,
    `  });`,
    ``,
    `  await saveAttempt({`,
    `    orderRef,`,
    `    orderId,`,
    `    amount: created.amount,`,
    `    currency: created.currency,`,
    `    providerOrderId: created.providerOrderId,`,
    `    status: created.status,`,
    `    refundedAmount: 0,`,
    `  });`,
    ``,
    `  // Never forward created.raw to the browser: return only what checkout needs.`,
    `  return { orderRef, provider: PROVIDER, mode: payments.mode, amount: created.amount, currency: created.currency, checkout: created.checkout };`,
    `}`,
    ``,
    `// ------------------------------------------------------------------------------------------`,
    `// 2. Customer returns from the gateway (POST|GET /api/payments/callback)`,
    `// ------------------------------------------------------------------------------------------`,
    ``,
    `export interface ConfirmResult {`,
    `  ok: boolean;`,
    `  orderRef?: string;`,
    `  status: PaymentStatus;`,
    `  reason?: string;`,
    `}`,
    ``,
    `/**`,
    ` * \`query\` = URL query params, \`body\` = POSTed form fields or JSON (from the gateway or our own JS).`,
    ` * Both are attacker-controlled until verified.`,
    ` */`,
    `export async function confirmPayment(query: Record<string, string>, body: Record<string, string> = {}): Promise<ConfirmResult> {`,
    `  // orderRef is OUR query param (added to returnUrl above). Strip it before verification: some`,
    `  // gateways (e.g. Paytm) checksum every field they sent, and ours is not one of them.`,
    `  const { orderRef: ourRef, ...queryRest } = query;`,
    `  const payload: Record<string, string> = { ...queryRest, ...body };`,
    orderRefField
      ? `  const orderRef = ourRef ?? payload['${orderRefField}']; // ${cap.displayName} also echoes it as ${orderRefField}`
      : `  const orderRef = ourRef;`,
    `  if (!orderRef) return { ok: false, status: 'unknown', reason: 'Missing orderRef' };`,
    ``,
    `  const attempt = await findAttempt(orderRef);`,
    `  if (!attempt) return { ok: false, orderRef, status: 'unknown', reason: 'Unknown orderRef' };`,
    `  // Reloads and double POSTs are normal; answer from our records once the attempt is final.`,
    `  if (attempt.status === 'captured' || attempt.status === 'refunded' || attempt.status === 'partially_refunded') {`,
    `    return { ok: true, orderRef, status: attempt.status };`,
    `  }`,
    ``,
    `  // Signature/hash check, bound to the orderRef and amount WE expect (prevents payload swapping).`,
    `  const verification = await payments.verifyPayment(PROVIDER, { payload, orderRef, expectedAmount: attempt.amount });`,
    `  if (!verification.valid) {`,
    `    payments.logger.warn('payment.verification_failed', { orderRef, reason: verification.reason });`,
    `    return { ok: false, orderRef, status: 'unknown', reason: 'Payment could not be verified' };`,
    `  }`,
    ``,
    `  // Second opinion from the gateway's status API, unless verification already was one.`,
    `  const confirmed =`,
    `    verification.verifiedVia === 'status_api'`,
    `      ? { status: verification.status, amount: verification.amount, providerPaymentId: verification.providerPaymentId }`,
    `      : await payments.getPaymentStatus(PROVIDER, { orderRef, providerOrderId: attempt.providerOrderId });`,
    ``,
    `  const status = await applyStatus(attempt, confirmed.status, confirmed.amount, confirmed.providerPaymentId ?? verification.providerPaymentId);`,
    `  return { ok: status === 'captured', orderRef, status };`,
    `}`,
    ``,
    `/** The only function that moves an attempt to a new state. Safe to call repeatedly. */`,
    `async function applyStatus(attempt: PaymentAttempt, status: PaymentStatus, amount: number | undefined, providerPaymentId?: string): Promise<PaymentStatus> {`,
    `  if (status === 'captured' && amount !== undefined && amount !== attempt.amount) {`,
    `    // Never fulfil on an amount mismatch. Alert a human; this is either a bug or tampering.`,
    `    payments.logger.error('payment.amount_mismatch', { orderRef: attempt.orderRef, expected: attempt.amount, got: amount });`,
    `    return 'unknown';`,
    `  }`,
    `  const wasCaptured = attempt.status === 'captured';`,
    `  const next: PaymentAttempt = { ...attempt, status, providerPaymentId: providerPaymentId ?? attempt.providerPaymentId };`,
    `  await saveAttempt(next);`,
    `  if (status === 'captured' && !wasCaptured) await fulfilOrder(next);`,
    `  return status;`,
    `}`,
    ``,
    `// ------------------------------------------------------------------------------------------`,
    `// 3. Webhooks (POST /api/payments/webhook). The route MUST pass the raw, unparsed body.`,
    `// ------------------------------------------------------------------------------------------`,
    ``,
    `async function onWebhookEvent(event: NormalizedWebhookEvent): Promise<void> {`,
    `  const attempt = event.orderRef`,
    `    ? await findAttempt(event.orderRef)`,
    `    : event.providerOrderId ? await findAttemptByProviderOrderId(event.providerOrderId) : undefined;`,
    `  if (!attempt) {`,
    `    // Not ours (another app on the same gateway account) or created before this code existed. Ack it.`,
    `    payments.logger.info('webhook.ignored', { type: event.type, orderRef: event.orderRef });`,
    `    return;`,
    `  }`,
    `  switch (event.type) {`,
    `    case 'payment.succeeded':`,
    `    case 'payment.failed':`,
    `    case 'payment.pending':`,
    `    case 'payment.authorized': {`,
    UNSIGNED_WEBHOOK_BODY.has(cap.provider)
      ? lines(
          `      // ${cap.displayName} does not sign the webhook body, so ask the gateway before changing state.`,
          `      if (payments.mode !== 'mock') {`,
          `        const s = await payments.getPaymentStatus(PROVIDER, { orderRef: attempt.orderRef, providerOrderId: attempt.providerOrderId });`,
          `        await applyStatus(attempt, s.status, s.amount, s.providerPaymentId);`,
          `        return;`,
          `      }`,
        )
      : `      // The body is signed by ${cap.displayName}, and the handler already verified it.`,
    `      const status: PaymentStatus = event.type === 'payment.succeeded' ? 'captured' : event.type === 'payment.failed' ? 'failed' : (event.status ?? 'pending');`,
    `      // Gateways can deliver "failed" after "succeeded" for a retried attempt; never downgrade a capture.`,
    `      if (attempt.status === 'captured' && status !== 'captured') return;`,
    `      await applyStatus(attempt, status, event.amount, event.providerPaymentId);`,
    `      return;`,
    `    }`,
    `    case 'refund.processed': {`,
    `      const refundedAmount = Math.min(attempt.amount, attempt.refundedAmount + (event.amount ?? attempt.amount - attempt.refundedAmount));`,
    `      const status: PaymentStatus = refundedAmount >= attempt.amount ? 'refunded' : 'partially_refunded';`,
    `      await saveAttempt({ ...attempt, refundedAmount, status });`,
    `      return;`,
    `    }`,
    `    case 'refund.failed':`,
    `      payments.logger.error('refund.failed', { orderRef: attempt.orderRef, refundRef: event.refundRef });`,
    `      return; // TODO: alert your finance team`,
    subs
      ? lines(
          `    case 'subscription.activated':`,
          `    case 'subscription.charged':`,
          `    case 'subscription.halted':`,
          `    case 'subscription.cancelled':`,
          `      // TODO: UPDATE subscriptions SET status = ... WHERE provider_subscription_id = ...`,
          `      payments.logger.info('subscription.event', { type: event.type, id: event.id });`,
          `      return;`,
        )
      : false,
    `    default:`,
    `      payments.logger.info('webhook.unhandled', { type: event.type, providerEventType: event.providerEventType });`,
    `  }`,
    `}`,
    ``,
    `/**`,
    ` * verify signature -> dedupe by event id -> onWebhookEvent -> { status, body }.`,
    ` * 2xx tells the gateway to stop retrying; 5xx (your handler threw) makes it retry.`,
    ` * The default dedupe store is in-memory: pass \`dedupe\` backed by Redis/Postgres when you run more than one instance.`,
    ` */`,
    `export const handleWebhook = createWebhookHandler({ client: payments, provider: PROVIDER, onEvent: onWebhookEvent });`,
    refunds
      ? lines(
          ``,
          `// ------------------------------------------------------------------------------------------`,
          `// 4. Refunds (POST /api/payments/refund). Admin only.`,
          `// ------------------------------------------------------------------------------------------`,
          ``,
          `/**`,
          ` * Placeholder auth: a shared bearer token. Replace with your real session/role check`,
          ` * (e.g. \`if (!session.user.roles.includes('finance')) throw new HttpError(403, ...)\`).`,
          ` */`,
          `export function assertAdmin(authorization: string | null | undefined): void {`,
          `  const expected = process.env.ADMIN_API_TOKEN;`,
          `  const given = authorization?.replace(/^Bearer\\s+/i, '') ?? '';`,
          `  const ok = !!expected && given.length === expected.length && timingSafeEqual(Buffer.from(given), Buffer.from(expected));`,
          `  if (!ok) throw new HttpError(401, 'Admin authentication required.');`,
          `}`,
          ``,
          `export async function refundPayment(body: unknown): Promise<{ refundRef: string; status: string; amount?: number }> {`,
          `  const { orderRef, amount, reason } = (body ?? {}) as { orderRef?: unknown; amount?: unknown; reason?: unknown };`,
          `  if (typeof orderRef !== 'string') throw new HttpError(400, 'orderRef is required.');`,
          `  const attempt = await findAttempt(orderRef);`,
          `  if (!attempt) throw new HttpError(404, 'Unknown orderRef.');`,
          `  if (attempt.status !== 'captured' && attempt.status !== 'partially_refunded') {`,
          `    throw new HttpError(409, \`Payment is \${attempt.status}; only captured payments can be refunded.\`);`,
          `  }`,
          `  const refundable = attempt.amount - attempt.refundedAmount;`,
          `  if (amount !== undefined && (typeof amount !== 'number' || !Number.isInteger(amount) || amount <= 0 || amount > refundable)) {`,
          `    throw new HttpError(400, \`amount must be an integer number of paise between 1 and \${refundable}.\`);`,
          `  }`,
          `  // refundRef is the idempotency key: the SDK never refunds twice for the same refundRef.`,
          `  // TODO: persist it with the admin's request id BEFORE calling, and reuse it if the admin retries.`,
          `  const refundRef = \`rf_\${randomBytes(8).toString('hex')}\`;`,
          `  const result = await payments.refund(`,
          `    PROVIDER,`,
          `    {`,
          `      orderRef,`,
          `      providerPaymentId: attempt.providerPaymentId,`,
          `      amount: amount as number | undefined, // undefined = full refund`,
          `      refundRef,`,
          `      reason: typeof reason === 'string' ? reason.slice(0, 200) : undefined,`,
          `    },`,
          `  );`,
          `  // The final state arrives by webhook (refund.processed); refunds take days to reach the customer.`,
          `  return { refundRef, status: result.status, amount: result.amount };`,
          `}`,
        )
      : false,
    subs
      ? lines(
          ``,
          `// ------------------------------------------------------------------------------------------`,
          `// 5. Subscriptions (POST /api/payments/subscription)`,
          `// ------------------------------------------------------------------------------------------`,
          ``,
          `export async function startSubscription(body: unknown): Promise<{ subscriptionRef: string; providerSubscriptionId: string; status: string; checkout?: CheckoutAction }> {`,
          `  const customerOrderId = (body as { orderId?: unknown } | null)?.orderId;`,
          `  const planId = process.env.PAYMENTS_PLAN_ID;`,
          `  if (!planId) throw new HttpError(500, 'PAYMENTS_PLAN_ID is not set.');`,
          `  // TODO: take the customer from the logged-in session, not the request body.`,
          `  const customer = typeof customerOrderId === 'string' ? await getOrderCustomer(customerOrderId) : undefined;`,
          `  const subscriptionRef = \`sub_\${randomBytes(8).toString('hex')}\`;`,
          `  const sub = await payments.createSubscription(PROVIDER, {`,
          `    subscriptionRef,`,
          `    providerPlanId: planId,`,
          `    customer,`,
          `    totalCount: 12, // billing cycles; required by some gateways (Razorpay), ignored by others`,
          `    // Activation is confirmed by the subscription.activated webhook, not by this redirect.`,
          `    returnUrl: \`\${baseUrl()}${opts.resultPath}?subscriptionRef=\${subscriptionRef}\`,`,
          `  });`,
          `  // TODO: INSERT INTO subscriptions (ref, provider_subscription_id, status) VALUES (...)`,
          `  return { subscriptionRef, providerSubscriptionId: sub.providerSubscriptionId, status: sub.status, checkout: sub.checkout };`,
          `}`,
        )
      : false,
    ``,
    `// ------------------------------------------------------------------------------------------`,
    `// Dev only: finish a payment in PAYMENTS_MODE=mock (POST /api/payments/mock-complete).`,
    `// ------------------------------------------------------------------------------------------`,
    ``,
    `export async function mockComplete(body: unknown): Promise<ConfirmResult> {`,
    `  if (payments.mode !== 'mock') throw new HttpError(404, 'Not found');`,
    `  const { orderRef, outcome } = (body ?? {}) as { orderRef?: unknown; outcome?: unknown };`,
    `  if (typeof orderRef !== 'string') throw new HttpError(400, 'orderRef is required.');`,
    `  const { callbackPayload } = payments.mockGateway(PROVIDER).complete(orderRef, outcome === 'failure' ? 'failure' : 'success');`,
    `  // Run the exact same verification path a real gateway callback would take.`,
    `  return confirmPayment({ orderRef }, callbackPayload);`,
    `}`,
    ``,
  );
}
