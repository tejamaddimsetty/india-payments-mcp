import type { ProviderCapabilities } from '../../core/capabilities.js';

export type Feature = 'checkout' | 'webhooks' | 'refunds' | 'subscriptions';

export interface GeneratedFile {
  path: string;
  language: string;
  contents: string;
}

/** Everything a template needs to render. Built once in generateIntegration. */
export interface TemplateContext {
  cap: ProviderCapabilities;
  features: ReadonlySet<Feature>;
  /** Callback/redirect styles to support in the callback route. */
  orderRefField?: string;
}

export const SDK_PACKAGE = 'india-payments-mcp';

/** Env vars the generated server reads, independent of the provider. */
export const COMMON_ENV = [
  { env: 'PAYMENTS_MODE', comment: 'mock (no network, no keys) | sandbox | live', example: 'mock' },
  { env: 'PAYMENTS_PROVIDERS', comment: 'Comma-separated gateways this app may use', example: '' },
  { env: 'PUBLIC_BASE_URL', comment: 'Public HTTPS origin of this app. Gateways redirect/POST back here. Use your tunnel URL in development.', example: 'http://localhost:3000' },
] as const;

export function envFile(ctx: TemplateContext): GeneratedFile {
  const { cap, features } = ctx;
  const lines: string[] = [
    `# ${cap.displayName} integration generated by india-payments-mcp.`,
    '# Copy to .env (or .env.local for Next.js) and fill in. NEVER commit the filled-in file.',
    '# Values marked SECRET must only ever exist on the server.',
    '',
  ];
  for (const c of COMMON_ENV) {
    lines.push(`# ${c.comment}`);
    lines.push(`${c.env}=${c.env === 'PAYMENTS_PROVIDERS' ? cap.provider : c.example}`);
  }
  lines.push('');
  lines.push(`# --- ${cap.displayName} credentials (from ${cap.dashboardUrl ?? cap.website}) ---`);
  for (const spec of cap.credentials) {
    lines.push(`# ${spec.required ? 'required' : 'optional'}${spec.secret ? ', SECRET' : ''}: ${oneLine(spec.description)}`);
    lines.push(`${spec.env}=`);
  }
  if (features.has('refunds')) {
    lines.push('');
    lines.push('# Shared secret for the admin-only refund route. Replace with your real auth.');
    lines.push('ADMIN_API_TOKEN=');
  }
  if (features.has('subscriptions')) {
    lines.push('');
    lines.push('# Provider plan/price id the subscription route subscribes customers to.');
    lines.push('PAYMENTS_PLAN_ID=');
  }
  lines.push('');
  lines.push('# Optional: append-only JSON-lines audit log of every payment mutation.');
  lines.push('PAYMENTS_AUDIT_LOG=');
  return { path: '.env.example', language: 'dotenv', contents: lines.join('\n') + '\n' };
}

export function envVarsFor(ctx: TemplateContext): string[] {
  const vars: string[] = COMMON_ENV.map((c) => c.env);
  vars.push(...ctx.cap.credentials.map((c) => c.env));
  if (ctx.features.has('refunds')) vars.push('ADMIN_API_TOKEN');
  if (ctx.features.has('subscriptions')) vars.push('PAYMENTS_PLAN_ID');
  return vars;
}

export function oneLine(s: string): string {
  return s.replace(/\s+/g, ' ').trim();
}

/** Indent every line of a block by n spaces (empty lines stay empty). */
export function indent(block: string, n: number): string {
  const pad = ' '.repeat(n);
  return block
    .split('\n')
    .map((l) => (l.length ? pad + l : l))
    .join('\n');
}

/** Join template pieces, dropping falsy ones, so optional sections disappear cleanly. */
export function lines(...parts: Array<string | false | undefined | null>): string {
  return parts.filter((p): p is string => typeof p === 'string').join('\n');
}

export function has(ctx: TemplateContext, f: Feature): boolean {
  return ctx.features.has(f);
}
